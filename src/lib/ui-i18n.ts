type Labels = string[] | Record<string, string>;
type Cases = typeof casesEn & { typeLabels?: Record<string, string> };
export type Case = Cases["cases"][number];
type LeadForm = typeof leadFormEn & { concernsLabels?: Labels };
type Contact = typeof contactEn & { topicsLabels?: Labels; replyViaLabels?: Labels };

export const casesFor = (locale: Locale): Cases => (locale === "es" ? (casesEs as Cases) : casesEn);
export const caseTypeLabel = (locale: Locale, type: string) => casesFor(locale).typeLabels?.[type] ?? type;
export const caseDisclaimer = (locale: Locale) => casesFor(locale).disclaimer;
export const formContent = (locale: Locale): { leadForm: LeadForm; contact: Contact; site: typeof siteEn } =>
  locale === "es" ? { leadForm: esLeadForm(), contact: esContact(), site: siteEs } : { leadForm: leadFormEn, contact: contactEn, site: siteEn };
const esLeadForm = () => leadFormEs as unknown as LeadForm;
const esContact = () => contactEs as unknown as Contact;

export function labelOf(values: readonly string[], labels: Labels | undefined, value: string): string {
  if (!labels) return value;
  if (Array.isArray(labels)) {
    const i = values.indexOf(value);
    return i >= 0 && labels[i] ? labels[i] : value;
  }
  return labels[value] ?? value;
}

/** Fills `{key}` placeholders. */
export const tpl = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));

