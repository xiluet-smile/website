// Generates public/_redirects for Cloudflare Pages from scripts/redirects.txt plus a
// trailing-slash → canonical 301 for every live route (EN and ES). Run by `npm run build`.
import { readFileSync, writeFileSync } from "node:fs";

const pages = JSON.parse(readFileSync("src/content/pages.json", "utf8"));
const esMap = Object.fromEntries(
  [...readFileSync("src/lib/i18n.ts", "utf8").matchAll(/^\s*"(\/[^"]*)": "(\/es[^"]*)",?$/gm)].map((m) => [m[1], m[2]]),
);
const live = new Set();
for (const p of Object.keys(pages)) {
  live.add(p);
  live.add(esMap[p] ?? (p === "/" ? "/es" : `/es${p}`));
}

const lines = [];
const manual = [];
for (const raw of readFileSync("scripts/redirects.txt", "utf8").split("\n")) {
  const line = raw.trim();
  if (!line || line.startsWith("#")) continue;
  const [from, to] = line.split(/\s+/);
  if (!from || !to) throw new Error(`Bad redirect line: ${raw}`);
  if (!live.has(to)) throw new Error(`Redirect target is not a live route (would chain or 404): ${from} -> ${to}`);
  manual.push([from.replace(/\/+$/, "") || "/", to]);
}
const seen = new Set();
lines.push("# Generated by scripts/build-redirects.mjs from scripts/redirects.txt. Do not edit by hand.");
lines.push("# Host canonicalisation (www -> apex) is in functions/_middleware.ts; Pages _redirects cannot match on host.");
lines.push("");
lines.push("# Old URLs -> final URLs (301), each with and without the trailing slash.");
for (const [from, to] of manual) {
  for (const src of from === "/" ? ["/"] : [from, `${from}/`]) {
    if (seen.has(src) || live.has(src)) continue; // never shadow a live route
    seen.add(src);
    lines.push(`${src} ${to} 301`);
  }
}
lines.push("");
lines.push("# Trailing-slash versions of every live page -> no-slash canonical (301 instead of the Pages default 308).");
for (const p of [...live].sort()) {
  if (p === "/") continue;
  const src = `${p}/`;
  if (seen.has(src)) continue;
  seen.add(src);
  lines.push(`${src} ${p} 301`);
}
writeFileSync("public/_redirects", lines.join("\n") + "\n");
console.log(`_redirects: ${manual.length} old URLs, ${live.size - 1} trailing-slash rules, ${seen.size} rules total`);
